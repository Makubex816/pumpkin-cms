import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { canonicalBaseUrlFromAnswers, defaultForbiddenRoutes, getAnswerForms, isPausedTenantDryRunApproved, normalizeRoute, slugFromRoute } from "./answers-validator.mjs";

const schemaVersion = "1.0.0";
const packageVersion = "0.2.0";

export function generatePackagePlan(answers) {
  const tenantId = answers.tenant.tenantId;
  const siteKey = answers.tenant.siteKey;
  const approvedRoutes = answers.routing.approvedRoutes.map((route) => normalizeRoute(route));
  const forbiddenRoutes = uniqueRoutes([...(answers.routing.forbiddenRoutes ?? []), ...defaultForbiddenRoutes]);
  const forms = getAnswerForms(answers);
  const pageFiles = answers.pages.map((page) => generatePageFile(answers, page));
  const files = [
    "README.md",
    "manifest.json",
    "tenant.json",
    "site.json",
    "routes.json",
    ...pageFiles.map((page) => page.relativePath),
    "media-assets.json",
    "forms.json",
    "seo.json",
    "theme.json",
    "redirects.json"
  ];

  return [
    textFile("README.md", renderGeneratedReadme(answers)),
    jsonFile("manifest.json", withoutUndefined({
      schemaVersion,
      packageVersion,
      tenantId,
      siteKey,
      createdFor: answers.tenant.tenantDisplayName,
      files,
      validation: {
        status: "not-run",
        externalMutationAllowed: false
      },
      pausedTenantDryRunApproval: packagePausedTenantDryRunApproval(answers)
    })),
    jsonFile("tenant.json", {
      schemaVersion,
      tenantId,
      siteKey,
      displayName: answers.tenant.tenantDisplayName,
      businessType: answers.tenant.businessType,
      cmsTenantSlug: answers.tenant.cmsTenantSlug,
      status: "intake-draft",
      tenantApiKeyPlaceholder: "TENANT_API_KEY_RUNTIME_ONLY",
      relatedTenants: [],
      pausedRelatedTenants: isPausedTenantDryRunApproved(answers) ? [answers.pausedTenantDryRunApproval.tenant] : []
    }),
    jsonFile("site.json", withoutUndefined({
      schemaVersion,
      tenantId,
      siteKey,
      primaryDomain: answers.domains.primaryDomain,
      wwwDomain: answers.domains.wwwDomain,
      mediaDomain: answers.domains.mediaDomain,
      stagingHostname: answers.domains.stagingHostname,
      deploymentProfileId: answers.builderProfile.deploymentProfile,
      canonicalHost: answers.domains.canonicalHost
    })),
    jsonFile("routes.json", {
      schemaVersion,
      tenantId,
      siteKey,
      approvedRoutes,
      forbiddenRoutes,
      wwwBehavior: answers.domains.canonicalHost === "www" ? "primary-host" : "canonical-only",
      notes: "Generated by the local/offline Phase 2B-2 import package builder hardening flow."
    }),
    ...pageFiles,
    jsonFile("media-assets.json", {
      schemaVersion,
      tenantId,
      siteKey,
      assets: answers.media.map((asset) => ({
        mediaId: asset.mediaId,
        fileName: asset.fileName,
        kind: asset.kind ?? "image",
        altText: asset.altText,
        sourceStatus: asset.sourceStatus ?? "placeholder",
        publicUrl: asset.publicUrl
      }))
    }),
    jsonFile("forms.json", {
      schemaVersion,
      tenantId,
      siteKey,
      forms: forms.map((form) => {
        const leadRecipientRef = form.leadRecipientRef;
        return withoutUndefined({
          formId: form.formId,
          displayName: form.displayName,
          deliveryMode: form.deliveryMode ?? "no-email",
          leadRecipientRef,
          recipientGroup: form.recipientGroup ?? leadRecipientRef,
          staticEndpointRef: form.staticEndpointRef,
          domainRoutingKey: form.domainRoutingKey,
          mailboxOwner: form.mailboxOwner,
          fields: form.fields,
          consentNoticeStatus: form.consentNoticeStatus ?? "pending-review",
          rollbackMode: form.rollbackMode ?? "disable-form"
        });
      })
    }),
    jsonFile("seo.json", {
      schemaVersion,
      tenantId,
      siteKey,
      defaultRobots: answers.seo.defaultRobots,
      canonicalBaseUrl: canonicalBaseUrl(answers),
      sitemapPolicy: answers.seo.sitemapPolicy ?? "disabled-until-final-gate",
      indexingFinalGate: true
    }),
    jsonFile("theme.json", {
      schemaVersion,
      tenantId,
      siteKey,
      themeId: `${tenantId}-default`,
      displayName: `${answers.tenant.tenantDisplayName} Default Theme`,
      navigation: answers.pages.map((page) => ({
        label: page.navLabel ?? page.title,
        href: normalizeRoute(page.route)
      })),
      colors: {
        primary: "#1E6B68",
        accent: "#D49A2A",
        background: "#FFFFFF",
        text: "#1F2933"
      }
    }),
    jsonFile("redirects.json", {
      schemaVersion,
      tenantId,
      siteKey,
      redirects: []
    })
  ];
}

export async function writePackagePlan(files, outputDirectory) {
  await mkdir(outputDirectory, { recursive: true });
  for (const file of files) {
    const absolutePath = path.join(outputDirectory, file.relativePath);
    await mkdir(path.dirname(absolutePath), { recursive: true });
    await writeFile(absolutePath, file.content, "utf8");
  }
}

function generatePageFile(answers, page) {
  const route = normalizeRoute(page.route);
  const slug = page.slug ?? slugFromRoute(route);
  const canonicalUrl = `${canonicalBaseUrl(answers)}${route === "/" ? "/" : route}`;
  const blocks = page.blocks ?? defaultBlocks(page);

  return jsonFile(path.posix.join("pages", `${slug}.json`), {
    schemaVersion,
    tenantId: answers.tenant.tenantId,
    siteKey: answers.tenant.siteKey,
    slug,
    route,
    title: page.title,
    status: page.status ?? "draft",
    seo: {
      title: page.seoTitle ?? page.title,
      description: page.seoDescription,
      robots: page.robots ?? answers.seo.defaultRobots,
      canonicalUrl
    },
    blocks,
    notes: "Generated placeholder page from local/offline builder answers."
  });
}

function defaultBlocks(page) {
  const blocks = [
    {
      type: "content",
      heading: page.title
    }
  ];

  if (Array.isArray(page.mediaRefs)) {
    for (const mediaId of page.mediaRefs) {
      blocks.push({ type: "image", mediaId });
    }
  }

  if (page.formRef) {
    blocks.push({ type: "form", formId: page.formRef });
  }

  return blocks;
}

function canonicalBaseUrl(answers) {
  return canonicalBaseUrlFromAnswers(answers);
}

function jsonFile(relativePath, data) {
  return {
    relativePath,
    content: `${JSON.stringify(data, null, 2)}\n`,
    data
  };
}

function textFile(relativePath, content) {
  return {
    relativePath,
    content: content.endsWith("\n") ? content : `${content}\n`
  };
}

